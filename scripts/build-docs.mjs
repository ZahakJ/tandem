// BUILD THE DOCUMENTATION PAGES.
//
//   node scripts/build-docs.mjs   →  site/docs/<slug>/index.html, site/docs/search.json
//
// The sources are Markdown files a reader can already open on GitHub: the
// user guide in docs/guide/*.md, plus a few documents that live elsewhere in
// the repository (ARCHITECTURE, RELEASING, CONTRIBUTING) and are rendered as
// pages rather than copied. A link between two sources is written as a
// relative path to the other .md file, so it works on GitHub, and is rewritten
// here to the page it became. A link to any other file in the repository
// becomes a link to that file on GitHub, except files under site/ (the
// screenshots), which are linked on the website itself.
//
// The output is not committed: the pages workflow runs this script and
// publishes site/. CI runs it too, and it exits 1 on a link to a page,
// heading or file that does not exist, in the docs or on the landing page.
// "Last updated" comes from git log, and is left out in a shallow clone.
//
// No dependencies. The Markdown renderer covers what these documents use
// (GitHub-flavoured blocks, tables, task lists, fenced code) and a few extras
// that still read well on GitHub:
//   > [!NOTE] or > **Tip:** …   a callout card (Note, Tip, Important, Warning, Caution)
//   <kbd>A</kbd> or :btn[A]     a controller button chip (A, B, X, Y, L1, Start…)
//   a paragraph of images       screenshots in a handheld frame, side by side;
//                               the image title ("…") is the caption
//   front matter summary:       overrides the summary under the title
// site/docs/docs.css and docs.js are written by hand.

