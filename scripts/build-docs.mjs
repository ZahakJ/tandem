let tracked = null;
/** Files a published link may point at: tracked or about to be, never ignored. */
function isTracked(path) {
  if (!tracked) {
    try {
      tracked = execFileSync("git", ["ls-files", "-co", "--exclude-standard"], { cwd: ROOT, encoding: "utf8" }).split("\n").filter(Boolean);
    } catch {
      tracked = null;
      return existsSync(join(ROOT, path));
    }
  }
  return tracked.includes(path) || tracked.some((t) => t.startsWith(`${path}/`));
}

/** Render one source. Pages sit one level below site/docs/. */
function renderPage(page, problems) {
  if (!existsSync(join(ROOT, page.file))) {
    problems.push(`${page.file}: missing (listed in SECTIONS)`);
    return { body: "", toc: [], ids: new Map(), links: [], title: page.title, summary: "" };
  }
  const md = readFileSync(join(ROOT, page.file), "utf8").replace(/\r\n/g, "\n");
  const from = posix.dirname(page.file);
  const toc = [];
  const ids = new Map();
  const links = [];
  const warn = (msg) => problems.push(`${page.file}: ${msg}`);
  let title = page.title;
  const ctx = {
    warn,
    heading(depth, html) {
      const text = plain(html);
      let id = slugify(text);
      const n = ids.get(id) ?? 0;
      ids.set(id, n + 1);
      if (n > 0) id = `${id}-${n}`;
      if (depth === 1) { title = text; return `<h1 id="${id}">${html}</h1>\n`; }
      if (depth <= 3) toc.push({ depth, id, text });
      return `<h${depth} id="${id}"><a class="anchor" href="#${id}" aria-hidden="true" tabindex="-1">#</a>${html}</h${depth}>\n`;
    },
    anchor(href, html, ttl) {
      const out = rewrite(href, from, links, warn);
      const ext = /^https?:/.test(out) ? ' rel="noreferrer"' : "";
      return `<a href="${esc(out)}"${ttl ? ` title="${esc(ttl)}"` : ""}${ext}>${html}</a>`;
    },
    image(href, alt, ttl) {
      const out = rewrite(href, from, links, warn);
      // A screenshot of the app is shown in a handheld's bezel, sized from the file so nothing jumps as it loads.
      const target = posix.normalize(posix.join(from, href.split("#")[0]));
      const size = /^https?:/.test(href) ? null : webpSize(join(ROOT, target));
      if (!alt) warn(`image without alt text: ${href}`);
      const screen = size ? (size.w / size.h > 1.4 ? "top" : "bottom") : null;
      const img = `<img src="${esc(out)}" alt="${esc(alt)}"${size ? ` width="${size.w}" height="${size.h}"` : ""} loading="lazy" decoding="async">`;
      return `<figure class="${screen ? `shot shot--${screen}` : "figure"}">${screen ? `<div class="shot__bezel"><div class="shot__glass">${img}</div></div>` : img}${ttl ? `<figcaption>${esc(ttl)}</figcaption>` : ""}</figure>`;
    },
  };
  // Optional front matter: `summary:` (and `title:`) override what is read from the text.
  let src = md;
  const front = {};
  const fm = /^---\n([\s\S]*?)\n---\n/.exec(src);
  if (fm) {
    for (const line of fm[1].split("\n")) {
      const kv = /^(\w+):\s*(.*)$/.exec(line);
      if (kv) front[kv[1]] = kv[2].replace(/^["']|["']$/g, "");
    }
    src = src.slice(fm[0].length);
  }
  let body = blocks(src.split("\n"), ctx);
  if (front.title) title = front.title;
  // The title and the paragraph under it move into the page's hero band.
  let lede = "";
  body = body.replace(/^<h1 id="[^"]*">[\s\S]*?<\/h1>\n/, "");
  const first = /^<p>([\s\S]*?)<\/p>\n/.exec(body);
  if (first) { lede = first[1]; body = body.slice(first[0].length); }
  const summary = front.summary ?? plain(lede);
  if (front.summary) lede = esc(front.summary);
  const words = plain(body.replace(/<pre[\s\S]*?<\/pre>/g, " ")).split(" ").length;
  return { body, toc, ids, links, title, summary, lede, minutes: Math.max(1, Math.round(words / 220)), updated: lastUpdated(page.file) };
}

/** Width and height of a WebP (or null), read from its header. */
function webpSize(path) {
  try {
    const b = readFileSync(path);
    if (b.toString("ascii", 0, 4) !== "RIFF" || b.toString("ascii", 8, 12) !== "WEBP") return null;
    const kind = b.toString("ascii", 12, 16);
    if (kind === "VP8X") return { w: 1 + b.readUIntLE(24, 3), h: 1 + b.readUIntLE(27, 3) };
    if (kind === "VP8 ") return { w: b.readUInt16LE(26) & 0x3fff, h: b.readUInt16LE(28) & 0x3fff };
    if (kind === "VP8L") {
      const n = b.readUInt32LE(21);
      return { w: (n & 0x3fff) + 1, h: ((n >> 14) & 0x3fff) + 1 };
    }
  } catch { /* not there or not readable: no size */ }
  return null;
}

/** The date of the last commit that touched `file`, or null. A shallow clone
 *  would date every page to its one commit, so it gives no date at all. */
let shallow = null;
function lastUpdated(file) {
  try {
    shallow ??= execFileSync("git", ["rev-parse", "--is-shallow-repository"], { cwd: ROOT, encoding: "utf8" }).trim() === "true";
    if (shallow) return null;
    return execFileSync("git", ["log", "-1", "--format=%cs", "--", file], { cwd: ROOT, encoding: "utf8" }).trim() || null;
  } catch {
    return null;
  }
}

/** Where a link in `from/` points once rendered. Collects page links for checking. */
function rewrite(href, from, links, warn) {
  if (/^(https?:|mailto:)/.test(href)) return href;
  if (href.startsWith("#")) { links.push({ page: null, hash: href.slice(1) }); return href; }
  const [path, hash = ""] = href.split("#");
  const target = posix.normalize(posix.join(from, path)).replace(/\/$/, "");
  const anchor = hash ? `#${hash}` : "";
  const page = BY_FILE.get(target);
  if (page) { links.push({ page, hash }); return `../${page.slug}/${anchor}`; }
  if (target.startsWith("..") || !isTracked(target)) { warn(`link to a file that is not in the repository: ${href}`); return href; }
  // Files the website itself serves (screenshots, the brand) are linked on the site. Pages sit two below site/.
  if (target.startsWith(`${SITE}/`) && !target.startsWith(`${OUT}/`)) return `../../${target.slice(SITE.length + 1)}${anchor}`;
  const abs = join(ROOT, target);
  const isDir = existsSync(abs) && statSync(abs).isDirectory();
  return `${REPO}/${isDir ? "tree" : "blob"}/main/${target}${anchor}`;
}

