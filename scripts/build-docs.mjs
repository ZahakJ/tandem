/** Checks every local link and asset on the landing page. Screenshots are optional and skipped. */
function checkLanding(rendered, problems) {
  const file = `${SITE}/index.html`;
  const html = readFileSync(join(ROOT, file), "utf8");
  const ids = new Set([...html.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]));
  const slugs = new Map(rendered.map((r) => [r.page.slug, r.ids]));
  for (const [, attr, value] of html.matchAll(/\s(href|src)="([^"]*)"/g)) {
    if (/^(https?:|mailto:|data:)/.test(value) || value === "") continue;
    const [path, hash = ""] = value.split("#");
    if (!path) { if (!ids.has(hash)) problems.push(`${file}: ${attr}="${value}" points at a missing id`); continue; }
    if (path === "./") continue;
    const docs = /^docs\/(?:([^/]+)\/)?$/.exec(path);
    if (docs) {
      if (!docs[1]) continue; // the overview
      const pageIds = slugs.get(docs[1]);
      if (!pageIds) problems.push(`${file}: link to a docs page that doesn't exist: ${value}`);
      else if (hash && !pageIds.has(hash)) problems.push(`${file}: link to a missing heading: ${value}`);
      continue;
    }
    if (!existsSync(join(ROOT, SITE, path))) problems.push(`${file}: ${attr}="${value}" doesn't exist`);
  }
}

export function build() {
  const problems = [];
  const files = new Map(); // repo-relative path → content
  const rendered = PAGES.map((p) => ({ page: p, ...renderPage(p, problems) }));
  const summaries = Object.fromEntries(rendered.map((r) => [r.page.slug, r.summary]));
  const search = [];
  rendered.forEach((r, i) => {
    for (const { page, hash } of r.links) {
      const ids = page ? rendered.find((x) => x.page === page).ids : r.ids;
      if (hash && !ids.has(hash) && !/-\d+$/.test(hash)) problems.push(`${r.page.file}: link to a missing heading ${page ? page.file : ""}#${hash}`);
    }
    if (!r.summary) problems.push(`${r.page.file}: no summary paragraph under the title`);
    files.set(`${OUT}/${r.page.slug}/index.html`, shell({
      ...r, current: r.page.slug, prev: PAGES[i - 1], next: PAGES[i + 1], file: r.page.file, base: "../",
    }));
    // The search index: every page and every h2/h3 in it, with the start of its text for a preview.
    for (const chunk of r.body.split(/(?=<h[23] id=")/)) {
      const m = /^<h([23]) id="([^"]+)">(.*?)<\/h\1>/.exec(chunk);
      const text = plain(chunk.replace(/<pre[\s\S]*?<\/pre>/g, " ").replace(/<h[1-3][^>]*>[\s\S]*?<\/h[1-3]>/, ""));
      search.push({
        p: r.page.title,
        u: `${r.page.slug}/${m ? `#${m[2]}` : ""}`,
        h: m ? plain(m[3].replace(/<a class="anchor"[^>]*>#<\/a>/, "")) : "",
        t: (m ? text : `${r.summary} ${text}`).slice(0, 150),
      });
    }
  });
  files.set(`${OUT}/index.html`, shell({ title: "Overview", body: homeBody(summaries), toc: [], current: null, file: null, summary: "The Tandem documentation: setup, the AYN Thor, systems and emulators, importing, resume, privacy and building from source.", base: "" }));
  files.set(`${OUT}/search.json`, `${JSON.stringify(search)}\n`);
  checkLanding(rendered, problems);

  // A page directory no longer in SECTIONS was left behind by a rename; remove it.
  const known = new Set(PAGES.map((p) => p.slug));
  for (const d of readdirSync(join(ROOT, OUT), { withFileTypes: true })) {
    const index = join(ROOT, OUT, d.name, "index.html");
    if (d.isDirectory() && !known.has(d.name) && existsSync(index) && readFileSync(index, "utf8").includes(MARKER)) rmSync(join(ROOT, OUT, d.name), { recursive: true });
  }
  for (const [path, content] of files) {
    const abs = join(ROOT, path);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
  }
  for (const p of problems) console.error(`build-docs: ${p}`);
  console.log(`build-docs: ${PAGES.length} pages → ${OUT}/${problems.length ? `, ${problems.length} problem(s)` : ""}`);
  if (problems.length) process.exitCode = 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
